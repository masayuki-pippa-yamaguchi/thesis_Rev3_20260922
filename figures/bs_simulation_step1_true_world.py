import numpy as np
import pandas as pd

np.random.seed(123)

# ---------------------------------------------------------
# 1. 真のパラメータの設定
# ---------------------------------------------------------

N = 5000  # サンプル数

# 真の μ（収益性）
mu_true = np.random.normal(loc=0.02, scale=0.03, size=N)

# 真の σ（市場ショック）
sigma_true = np.random.normal(loc=0.20, scale=0.05, size=N)

# 真の S（支援能力：0〜3）
S_true = np.random.choice([0,1,2,3], size=N, p=[0.25,0.25,0.25,0.25])

# 真の D（倒産閾値：対数正規）
D_true = np.random.lognormal(mean=-1.0, sigma=0.4, size=N)

# ---------------------------------------------------------
# 2. 真の係数（理論モデルの符号条件）
# ---------------------------------------------------------

a = 1.0   # μ の係数
b = 1.0   # σ の係数
c = 0.8   # S の係数
d = 1.2   # D の係数

# ---------------------------------------------------------
# 3. 真の潜在倒産距離 Z*
# ---------------------------------------------------------

Z_true = a*mu_true - b*sigma_true + c*S_true - d*D_true

# ---------------------------------------------------------
# 4. 真の倒産確率 p
# ---------------------------------------------------------

p_true = 1 / (1 + np.exp(-Z_true))

# ---------------------------------------------------------
# 5. 倒産ダミー（Bernoulli）
# ---------------------------------------------------------

default = np.random.binomial(n=1, p=p_true, size=N)

# ---------------------------------------------------------
# 6. データフレームにまとめる
# ---------------------------------------------------------

df_true = pd.DataFrame({
    "mu_true": mu_true,
    "sigma_true": sigma_true,
    "S_true": S_true,
    "D_true": D_true,
    "Z_true": Z_true,
    "p_true": p_true,
    "default": default
})

# ---------------------------------------------------------
# 7. 出力確認（ターミナルに表示）
# ---------------------------------------------------------

print(df_true.head())

# ---------------------------------------------------------
# 8. CSV 保存（Step2 が読み込むため）
# ---------------------------------------------------------

df_true.to_csv("figures/df_true.csv", index=False)
